field map[HEIGHT][WIDTH];

void clearMap(){
  for(int i=0; i<HEIGHT; i++){
    for(int j=0; j<WIDTH; j++){
      //f(j%2==0)
	//	map[i][j].symbol = '@';
	//    else
	//ap[i][j].symbol = ' ';
    if(map[i][j].symbol != mapBlueprint[i][j])
      map[i][j].symbol  = mapBlueprint[i][j];
  	map[i][j].visibility = 0;
    
    }
  }

}

void showMap(){
  printf("\033[H\033[J");
  for(int i=0; i<HEIGHT; i++){
    for(int j=0; j<WIDTH; j++){
      if(map[i][j].visibility==1)
	printf("\033[93m%c\033[m", map[i][j].symbol);
      else
	printf("\033[30m%c\033[m", map[i][j].symbol);
    }
    printf("\n");
  }
  fflush(stdout);
}

void drawLine(point a0, point a1){
  int dx = abs(a1.x-a0.x), sx = a0.x<a1.x ? 1 : -1;
  int dy = -abs(a1.y-a0.y), sy = a0.y<a1.y ? 1 : -1;
  int err = dx+dy, e2;

  for(;;){
    if(a0.x>HEIGHT||a0.x<0||a0.y>=WIDTH||a0.y<0){
      break;
    }
    if(map[a0.x][a0.y].visibility==0)
      map[a0.x][a0.y].visibility = 1;
    if(map[a0.x][a0.y].symbol!='.'){
      break;
    }
    if(a0.x==a1.x && a0.y==a1.y)
      break;
    e2 = 2 *err;
    if(e2>= dy){
      err+=dy;
      a0.x +=sx;
    }
    if(e2<=dx){
      err+=dx;
      a0.y += sy;
    }
  }
    
}
